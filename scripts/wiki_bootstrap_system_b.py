"""Bootstrap the System B wiki — macro + meta skeleton pages only.

Per-ticker pages are NOT bootstrapped here. Stage 4 (Journal) auto-bootstraps
wiki pages on-demand when System B first commits to a new ticker.

Usage:
    .venv/bin/python scripts/wiki_bootstrap_system_b.py
    .venv/bin/python scripts/wiki_bootstrap_system_b.py --force   # overwrite existing

Idempotent: skips any page that already exists unless --force is given.
Prints a summary at the end listing what was written vs. skipped.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Resolve project root so the script works when called from any cwd.
_PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_PROJECT_ROOT))

from ai_hedge.wiki import templates  # noqa: E402 (after sys.path patch)
from ai_hedge.wiki.loader import parse_front_matter  # noqa: E402

WIKI_ROOT = _PROJECT_ROOT / "wiki"

# Pages to bootstrap: (target_path_relative_to_wiki, render_kwargs)
_PAGES: list[tuple[str, dict]] = [
    ("macro/regime.md",           {"page_kind": "regime"}),
    ("macro/scanner_state.md",    {"page_kind": "scanner_state"}),
    ("meta/lessons.md",           {"page_kind": "_lessons"}),       # special case below
    ("meta/open_positions.md",    {"page_kind": "_open_positions"}), # special case below
    ("meta/setup_patterns.md",    {"page_kind": "setup_patterns"}),
    ("meta/budget_state.md",      {"page_kind": "budget_state"}),
]


def _render_lessons() -> str:
    """Minimal lessons page matching System A's format — empty rows."""
    from ai_hedge.wiki.templates import _front_matter
    return _front_matter(
        name="trade lessons",
        target_words=1500,
        stale_after_days=90,
        summary="Running log of trade outcome lessons — one bullet per closed trade, written nightly by b_journal",
    ) + (
        "## Format\n\n"
        "Each lesson is one dated bullet:\n\n"
        "`[DATE] | [TICKER] | [SETUP TYPE] | [OUTCOME: +$X / -$X]"
        " | [WHY it worked or failed in 1 sentence]`\n\n"
        "The \"why\" should reference: the thesis at the time, the macro regime, "
        "which scanner setup triggered it.\n\n"
        "---\n\n"
        "## Patterns (auto-generated by Sunday compactor, last 30 days)\n\n"
        "| Setup Type | Trades | Wins | Win Rate | Avg P&L | Total P&L |\n"
        "|---|---|---|---|---|---|\n"
        "| _no data yet_ | — | — | — | — | — |\n\n"
        "## Lessons\n\n"
        "_No lessons yet — System B has not executed any trades._\n"
    )


def _render_open_positions() -> str:
    """Minimal open_positions page matching System A's format."""
    from ai_hedge.wiki.templates import _front_matter
    from datetime import date
    return _front_matter(
        name="open positions snapshot",
        target_words=600,
        stale_after_days=2,
        summary="Structured ledger view of currently-open and pending swing trades. Refreshed nightly.",
    ) + (
        "# Open Positions — Snapshot\n\n"
        "Snapshot taken: _pending_. Refreshed nightly by Stage 4 (b_journal).\n\n"
        "## Summary\n\n"
        "- Open positions: 0\n"
        "- Pending orders: 0\n"
        "- Net long count: 0\n"
        "- Net short count: 0\n"
        "- Tickers held: _none_\n\n"
        "## Open positions\n\n"
        "_none_\n\n"
        "## Pending orders\n\n"
        "_none_\n\n"
        "## Field definitions\n\n"
        "- **Dir**: `long` or `short`.\n"
        "- **Entry**: actual fill price for open positions; limit price for pending orders.\n"
        "- **Current**: most recent traded price at snapshot time.\n"
        "- **Days**: trading days between entry and snapshot (open positions only).\n"
        "- **Unreal $/%**: unrealized P&L from entry to current price.\n"
        "- **Run**: the run_id that originated this position.\n"
    )


def _render(page_kind: str) -> str:
    if page_kind == "_lessons":
        return _render_lessons()
    if page_kind == "_open_positions":
        return _render_open_positions()
    return templates.render(page_kind)


def bootstrap(force: bool = False) -> int:
    written: list[str] = []
    skipped: list[str] = []

    for rel_path, kwargs in _PAGES:
        target = WIKI_ROOT / rel_path
        target.parent.mkdir(parents=True, exist_ok=True)

        if target.exists() and not force:
            skipped.append(rel_path)
            print(f"  skipped (exists): wiki/{rel_path}")
            continue

        existed = target.exists()
        content = _render(kwargs["page_kind"])
        target.write_text(content)
        written.append(rel_path)
        action = "overwrote" if existed else "wrote"
        print(f"  {action}: wiki/{rel_path}")

    print()
    print("System B wiki bootstrap complete:")
    for p in written:
        print(f"  wrote: wiki/{p}")
    if skipped:
        print()
        print("Skipped (already exist — use --force to overwrite):")
        for p in skipped:
            print(f"  skipped: wiki/{p}")

    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing pages instead of skipping them.",
    )
    args = parser.parse_args(argv)
    return bootstrap(force=args.force)


if __name__ == "__main__":
    sys.exit(main())
